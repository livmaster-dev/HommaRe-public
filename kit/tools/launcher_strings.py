#!/usr/bin/env python3
"""Check the launcher's translations and build them into the app.

    tools/launcher_strings.py            # check
    tools/launcher_strings.py --write    # check, then write LauncherCatalog.swift

host/launcher/apple/launcher-strings.json holds the launcher's own words:
for each L10n member (LauncherStrings.swift) one text per language, with
{placeholders} for the member's arguments ("args"). This checks that every
language has every text, that each text has exactly the entry's placeholders,
that every t("key") in LauncherStrings.swift has an entry and passes the
placeholders it names, and that LauncherCatalog.swift is the JSON as it is
now. --write regenerates that file: the JSON in a Swift raw string, read
once at start, so the app needs no resource file for it. The native launcher
on Linux and Windows (host/launcher/linux/) embeds the JSON itself at build
time and prefers an entry's ".linux" variant where there is one (on
Windows its ".windows" one first).
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HERE = ROOT / "host/launcher/apple"
JSON = HERE / "launcher-strings.json"
SWIFT = HERE / "LauncherCatalog.swift"
STRINGS = HERE / "LauncherStrings.swift"
PH = re.compile(r"\{(\w+)\}")


def catalog_swift(text):
    if '"""#' in text:
        raise ValueError("launcher-strings.json holds the raw string's end")
    return ("// LauncherCatalog.swift - generated by tools/launcher_strings.py --write from\n"
            "// launcher-strings.json: edit that file, then run the tool.\n"
            "enum LauncherCatalog {\n"
            '    static let json = #"""\n' + text.rstrip("\n") + '\n"""#\n}\n')


def check(data):
    errors = []
    langs = [lang["code"] for lang in data["languages"]]
    if not langs or langs[0] != "en":
        errors.append("languages: English goes first (the fallback)")
    strings = data["strings"]
    for key, entry in strings.items():
        want = set(entry.get("args") or PH.findall(entry.get("en", "")))
        for lang in langs:
            text = entry.get(lang)
            if not isinstance(text, str) or not text.strip():
                errors.append("%s: no %s" % (key, lang))
            elif set(PH.findall(text)) != want:
                errors.append("%s [%s]: placeholders %s, want %s" % (key, lang, sorted(set(PH.findall(text))),
                                                                     sorted(want)))
        extra = set(entry) - set(langs) - {"args"} - {k for k in entry if k.startswith("_")}
        if extra:
            errors.append("%s: unknown fields %s" % (key, sorted(extra)))
    # Every t("key", [...]) the Swift source makes: an entry, with its placeholders.
    src = STRINGS.read_text()
    for m in re.finditer(r'\bt\("([\w.]+)"(?:,\s*\[([^\]]*)\])?\)', src):
        key, args = m.group(1), m.group(2) or ""
        if key not in strings:
            errors.append('LauncherStrings.swift: t("%s") has no entry' % key)
            continue
        passed = set(re.findall(r'"(\w+)":', args))
        want = set(strings[key].get("args") or PH.findall(strings[key]["en"]))
        if passed != want:
            errors.append('LauncherStrings.swift: t("%s") passes %s, the texts use %s' % (key, sorted(passed),
                                                                                       sorted(want)))
    return errors


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--write", action="store_true", help="write LauncherCatalog.swift")
    args = p.parse_args()
    text = JSON.read_text()
    data = json.loads(text)
    errors = check(data)
    swift = catalog_swift(text)
    if args.write and not errors:
        SWIFT.write_text(swift)
    elif not SWIFT.is_file() or SWIFT.read_text() != swift:
        errors.append("LauncherCatalog.swift is not launcher-strings.json as it is: run with --write")
    for e in errors:
        print(e)
    print("%d texts x %d languages: %s" % (len(data["strings"]), len(data["languages"]),
                                           "ok" if not errors else "%d problems" % len(errors)))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
