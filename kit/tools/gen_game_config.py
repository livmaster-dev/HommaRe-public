#!/usr/bin/env python3
"""Render games/<id>/game.toml into game_config.h and game_config.cmake.

    tools/gen_game_config.py --game-dir /abs/path/to/<game> --header OUT.h --cmake OUT.cmake

The header is what runtime/, dx/ and host/ include for every game-specific
value; the cmake fragment names the app and the image base for the build."""

import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import game_config  # noqa: E402

STRINGS = (("id", "RECOMP_GAME_ID"), ("name", "RECOMP_GAME_NAME"), ("app_name", "RECOMP_APP_NAME"),
           ("bundle_id", "RECOMP_BUNDLE_ID"), ("executable", "RECOMP_EXECUTABLE"),
           ("sha256", "RECOMP_EXE_SHA256"), ("guest_root", "RECOMP_GUEST_ROOT"))
ADDRESSES = (("image_base", "RECOMP_IMAGE_BASE"), ("entry_point", "RECOMP_ENTRY_POINT"),
             ("heap_base", "RECOMP_HEAP_BASE"), ("heap_extra_base", "RECOMP_HEAP_EXTRA_BASE"),
             ("heap_extra_size", "RECOMP_HEAP_EXTRA_SIZE"))


def c_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def c_hex(value):
    return "0x%08xu" % value


def c_string_list(values):
    """A brace initializer of C strings ending in a null pointer."""
    return "{" + "".join(c_string(v) + ", " for v in values) + "0}"


def render_header(cfg):
    game = cfg["game"]
    lines = ["/* generated by tools/gen_game_config.py from %s -- do not edit */" % cfg["source"],
             "#pragma once"]
    for key, macro in STRINGS:
        lines.append("#define %s %s" % (macro, c_string(game[key])))
    lines.append("#define RECOMP_PREVIOUS_APP_NAMES %s" % c_string_list(game["previous_app_names"]))
    # The game id as an identifier, for names that must differ between the
    # games one app carries (a game module's Objective-C classes).
    lines.append("#define RECOMP_GAME_SYMBOL %s" % "".join(c if c.isalnum() else "_" for c in game["id"]))
    for key, macro in ADDRESSES:
        lines.append("#define %s %s" % (macro, c_hex(game[key])))
    for field, value in zip(("MAJOR", "MINOR", "BUILD", "PLATFORM"),
                            game_config.windows_version(game["windows_version"])):
        lines.append("#define RECOMP_WINDOWS_%s %du" % (field, value))
    # Absolute: the developer's game lives beside game.toml, not under the kit.
    lines.append("#define RECOMP_DEVELOPER_EXE %s" % c_string(cfg["developer_exe_path"].as_posix()))
    lines.append("#define RECOMP_DEVELOPER_GAME_DIR %s" % c_string(cfg["developer_exe_path"].parent.as_posix()))
    lines.append("#define RECOMP_GAME_DIR %s" % c_string(Path(cfg["dir"]).resolve().as_posix()))
    # [translate] write_track = "protect": the translated stores do not mark
    # the renderer's lazy buffers, so dx/d3d9.cpp has to catch them by page
    # protection (and must not fall back to store marking).
    # The runtime half of [translate] fixed_guest_base; macOS only, as the
    # translated half (cmake/Translate.cmake).
    lines.append("#if defined(__APPLE__)\n#include <TargetConditionals.h>\n#endif")
    lines.append("#if defined(__APPLE__) && TARGET_OS_OSX\n#define RECOMP_GAME_FIXED_GUEST_BASE %d\n#else\n"
                 "#define RECOMP_GAME_FIXED_GUEST_BASE 0\n#endif"
                 % int(cfg["translate"].get("fixed_guest_base", False)))
    # No page protection in WebAssembly: the web build's stores mark instead
    # (cmake/Translate.cmake), so its runtime tracks by them.
    lines.append("#if defined(__EMSCRIPTEN__)\n#define RECOMP_GAME_WRITE_TRACK_PROTECT 0\n#else\n"
                 "#define RECOMP_GAME_WRITE_TRACK_PROTECT %d\n#endif"
                 % int(cfg["translate"].get("write_track", "stores") == "protect"))
    lines.append("#define RECOMP_KIT_DIR %s" % c_string(Path(__file__).resolve().parents[1].as_posix()))
    # The on-screen controls a fresh profile starts with, and how the pad maps
    # onto the keyboard/mouse or a real controller (games/stub/game.toml [controls]).
    controls = cfg["controls"]
    lines.append("#define RECOMP_CONTROLS_DEFAULT_LAYOUT %s" % c_string(controls["default_layout"]))
    lines.append("#define RECOMP_TOUCH_HOVER %d" % int(cfg["touch"]["gestures"] == "hover"))
    lines.append("#define RECOMP_IOS_PORTRAIT %d" % int(cfg["ios"]["portrait"]))
    # [ios] cfg_defaults as "file|key|value;" records.
    lines.append("#define RECOMP_IOS_CFG_DEFAULTS %s" % c_string("".join(
        "%s|%s|%s;" % (f, k, v)
        for f, kv in sorted(cfg["ios"]["cfg_defaults"].items()) for k, v in sorted(kv.items()))))
    # [ios] cfg_seeds as "file|source;" records.
    lines.append("#define RECOMP_IOS_CFG_SEEDS %s" % c_string("".join(
        "%s|%s;" % (f, s) for f, s in sorted(cfg["ios"]["cfg_seeds"].items()))))
    lines.append("#define RECOMP_TOUCH_PAN_GAIN %r" % float(cfg["touch"]["pan_gain"]))
    # [net] movable_udp_ports as "port," records.
    lines.append("#define RECOMP_NET_MOVABLE_UDP_PORTS %s" % c_string(
        "".join("%d," % p for p in cfg["net"]["movable_udp_ports"])))
    # [texts] as a pak path, "file;" records and "old|new;" records.
    texts = cfg["texts"]
    lines.append("#define RECOMP_TEXTS_PAK %s" % c_string(texts["pak"]))
    lines.append("#define RECOMP_TEXTS_FILES %s" % c_string("".join(f + ";" for f in texts["files"])))
    lines.append("#define RECOMP_TEXTS_REPLACE %s" % c_string(
        "".join("%s|%s;" % (k, v) for k, v in texts["replace"].items())))
    # [online]: the GS server-list host and the host's question about it.
    online = cfg["online"]
    lines.append("#define RECOMP_ONLINE_GSCONNECT_HOST %s" % c_string(online["gsconnect_host"]))
    lines.append("#define RECOMP_ONLINE_PROMPT_TITLE %s" % c_string(online["prompt_title"]))
    lines.append("#define RECOMP_ONLINE_PROMPT_TEXT %s" % c_string(online["prompt_text"]).replace("\n", "\\n"))
    lines.append("#define RECOMP_ONLINE_DEFAULT_SERVER %s" % c_string(online["default_server"]))
    lines.append("#define RECOMP_TOUCH_INVERT %s" % c_string(",".join(cfg["touch"]["invert"])))
    lines.append("#define RECOMP_CONTROLS_PAD %d" % ("off", "mapped", "native").index(controls["pad"]))
    lines.append("#define RECOMP_CONTROLS_MAPPED %s" % c_string(
        ";".join("%s=%s" % (k, controls["mapped"][k]) for k in sorted(controls["mapped"]))))
    native = controls["native"]
    lines.append("#define RECOMP_CONTROLS_XINPUT %d" % int(native["xinput"]))
    lines.append("#define RECOMP_CONTROLS_DINPUT %d" % int(native["dinput"]))
    lines.append("#define RECOMP_CONTROLS_NATIVE_AXES %s" % c_string(",".join(native["axes"])))
    lines.append("#define RECOMP_CONTROLS_NATIVE_BUTTONS %s" % c_string(",".join(native["buttons"])))
    lines.append("#define RECOMP_GUEST_SIZE %s" % c_hex(game["guest_size"]))
    lines.append("#define RECOMP_ANSI_CODEPAGE %du" % game.get("ansi_codepage", 1252))
    # [game] cpuid_sse: CPUID reports SSE and SSE2 (runtime/cpu.cpp), so the
    # game takes its SSE paths; RECOMP_CPUID_SSE=0 or 1 overrides.
    lines.append("#define RECOMP_GAME_CPUID_SSE %d" % int(game.get("cpuid_sse", False)))
    # [game] sockets: WinSock on the host's sockets (runtime/winsock.cpp);
    # RECOMP_SOCKETS=0 or 1 overrides.
    lines.append("#define RECOMP_GAME_SOCKETS %d" % int(game.get("sockets", False)))
    lines.append("#define RECOMP_RESUMABLE_STACKS %d" %
                 int(cfg["translate"].get("resumable_stacks", False)))
    lines.append("#define RECOMP_CD_AUDIO_TRACKS %s" % c_string_list(cfg.get("media", {}).get("cd_tracks", [])))
    # Auxiliary modules the loader maps beside the image: {name, developer path, sha256, base, size}.
    lines.append("#define RECOMP_AUX_MODULE_COUNT %d" % len(cfg["aux_modules"]))
    lines.append("#define RECOMP_AUX_MODULES {%s}" % ", ".join(
        '{%s, %s, %s, %s, 0x%08xu}' % (c_string(m["name"]), c_string(m["path"].as_posix()), c_string(m["sha256"]),
                                        c_hex(m["base"]), m["size"])
        for m in cfg["aux_modules"]) if cfg["aux_modules"] else "#define RECOMP_AUX_MODULES {{0, 0, 0, 0u, 0u}}")
    # The mod runtime's built-in game integrations (animation clock, native
    # options menu, settings persistence, sprite view) were written against
    # Populous and hook its routines by address. Another game turns them off.
    builtin = cfg.get("mods", {}).get("builtin", "populous")
    if builtin not in ("populous", "none"):
        raise ValueError('[mods] builtin must be "populous" or "none", not %r' % builtin)
    lines.append("#define RECOMP_MODS_BUILTIN_POPULOUS %d" % (1 if builtin == "populous" else 0))
    # One bit per settings-page row, in game_config.SETTINGS_ROWS order.
    mask = sum(1 << i for i, row in enumerate(game_config.SETTINGS_ROWS) if row in cfg["settings"]["rows"])
    lines.append("#define RECOMP_SETTINGS_ROWS 0x%03xu" % mask)
    lines.append("#define RECOMP_SETTINGS_FILTERING_DEFAULT %d" % cfg["settings"]["filtering_default"])
    lines.append("#define RECOMP_SETTINGS_FILTERING_KEY %s" % c_string(cfg["settings"]["filtering_key"]))
    lines.append("#define RECOMP_SETTINGS_PAGE_TABS %d" % (cfg["settings"]["page"] == "tabs"))
    lines.append("#define RECOMP_SMOOTH_SCALING %d" % (cfg["settings"]["scaling"] == "smooth"))
    # The launcher's data: what to call the game, where to get it, where an
    # install may be, and what an import copies (host/launcher/).
    launcher = cfg["launcher"]
    lines.append("#define RECOMP_LAUNCHER_TITLE %s" % c_string(launcher["title"]))
    lines.append("#define RECOMP_LAUNCHER_STORE_URL %s" % c_string(launcher["store"]))
    lines.append("#define RECOMP_LAUNCHER_INSTALL_NAMES %s" % c_string_list(launcher["install_names"]))
    lines.append("#define RECOMP_LAUNCHER_GOG_IDS %s" % c_string_list(launcher["gog_ids"]))
    lines.append("#define RECOMP_LAUNCHER_STEAM_IDS %s" % c_string_list(launcher["steam_ids"]))
    lines.append("#define RECOMP_LAUNCHER_MIN_FREE_MB %du" % launcher["min_free_mb"])
    lines.append("#define RECOMP_REQUIRED_DIRS %s" % c_string_list(cfg["setup"]["required_dirs"]))
    lines.append("#define RECOMP_BUNDLE_EXCLUDE %s" % c_string_list(cfg["bundle"]["exclude"]))
    for key, value in sorted(cfg.get("hooks", {}).items()):
        macro = "RECOMP_HOOK_" + key.upper()
        if isinstance(value, list):
            lines.append("#define %s_COUNT %d" % (macro, len(value)))
            lines.append("#define %s {%s}" % (macro, ", ".join(c_hex(v) for v in value)))
        else:
            lines.append("#define %s %s" % (macro, c_hex(value)))
    for key, entry in sorted(cfg.get("globals", {}).items()):
        macro = "RECOMP_GLOBAL_" + key.upper()
        lines.append("#define %s_ADDR %s" % (macro, c_hex(entry["addr"])))
        for field in ("size", "stride", "count"):
            if field in entry:
                lines.append("#define %s_%s %du" % (macro, field.upper(), entry[field]))
    return "\n".join(lines) + "\n"


def render_cmake(cfg):
    game = cfg["game"]
    lines = ["# generated by tools/gen_game_config.py from %s -- do not edit" % cfg["source"]]
    for key, macro in STRINGS[:5]:
        lines.append('set(%s "%s")' % (macro, game[key]))
    lines.append('set(RECOMP_IOS_DISPLAY_NAME "%s")' % cfg["ios"]["display_name"])
    # Info.plist arrays of the app's former names, for the macOS launcher.
    for key, macro in (("previous_app_names", "RECOMP_PREVIOUS_APP_NAMES_PLIST"),
                       ("previous_bundle_ids", "RECOMP_PREVIOUS_BUNDLE_IDS_PLIST")):
        lines.append('set(%s "%s")' % (macro, "".join("<string>%s</string>" % n for n in game[key])))
    # [ios] profile_files as "profile path|source path" list items.
    lines.append('set(RECOMP_IOS_PROFILE_FILES "%s")' % ";".join(
        "%s|%s" % (k, (Path(cfg["dir"]) / v).resolve().as_posix())
        for k, v in sorted(cfg["ios"]["profile_files"].items())))
    lines.append('set(RECOMP_MACOS_PROFILE_FILES "%s")' % ";".join(
        "%s|%s" % (k, (Path(cfg["dir"]) / v).resolve().as_posix())
        for k, v in sorted(cfg["macos"]["profile_files"].items())))
    # ui_mods as recipe paths (ui-mods/<name>.recipe under the game directory).
    for section, macro in (("ios", "RECOMP_IOS_UI_MODS"), ("macos", "RECOMP_MACOS_UI_MODS"),
                           ("web", "RECOMP_WEB_UI_MODS")):
        lines.append('set(%s "%s")' % (macro, ";".join(
            (Path(cfg["dir"]) / "ui-mods" / (name + ".recipe")).resolve().as_posix()
            for name in cfg[section]["ui_mods"])))
    # An iPhone may hold the app upright: the launcher stands either way; the
    # game's own window keeps to [ios] portrait (SDL_HINT_ORIENTATIONS in
    # host/sdl/platform_ui_ios.mm).
    lines.append('set(RECOMP_IOS_PHONE_ORIENTATIONS "%s")' % (
        "<string>UIInterfaceOrientationPortrait</string>"
        "<string>UIInterfaceOrientationLandscapeLeft</string>"
        "<string>UIInterfaceOrientationLandscapeRight</string>"))
    lines.append("set(RECOMP_IMAGE_BASE %s)" % c_hex(game["image_base"]))
    lines.append("set(RECOMP_HEAP_BASE %s)" % c_hex(game["heap_base"]))
    lines.append("set(RECOMP_GUEST_SIZE %s)" % c_hex(game["guest_size"]))
    lines.append("set(RECOMP_HEAP_EXTRA_BASE %s)" % c_hex(game["heap_extra_base"]))
    lines.append("set(RECOMP_HEAP_EXTRA_SIZE %s)" % c_hex(game["heap_extra_size"]))
    # [translate] store_hooks = false: a game with no DirectDraw locks drops the per-store
    # watch/dirty check from its translated code (RECOMP_WATCH then needs it back on).
    lines.append("set(RECOMP_STORE_HOOKS %d)" % int(cfg["translate"].get("store_hooks", True)))
    # [translate] write_track = "protect": stores into the renderer's lazy
    # buffers are caught by page protection (dx/d3d9.cpp), so the translated
    # code drops the per-store tracking compare (runtime/x86.h recomp_track).
    # [translate] fixed_guest_base: macOS maps the arena at a fixed address and
    # the translated code uses it as a constant (runtime/x86.h).
    # [translate] lean_calls: translated calls skip the profiler and
    # frame-watch checks (RECOMP_PROFILE / RECOMP_WATCH_FRAME need it off).
    lines.append("set(RECOMP_LEAN_CALLS %d)" % int(cfg["translate"].get("lean_calls", False)))
    lines.append("set(RECOMP_FIXED_GUEST_BASE %d)" % int(cfg["translate"].get("fixed_guest_base", False)))
    lines.append("set(RECOMP_WRITE_TRACK_STORES %d)"
                 % int(cfg["translate"].get("write_track", "stores") != "protect"))
    # The generated sources include this header before they define FN_<addr>,
    # which is how a game replaces one translated function with a native one.
    lines.append('set(RECOMP_OVERRIDE_HEADER "%s")'
                 % (cfg["overrides_header"].as_posix() if cfg.get("overrides_header") else ""))
    lines.append("set(RECOMP_AUX_MODULES %s)" % ";".join(m["key"] for m in cfg["aux_modules"]))
    lines.append('set(RECOMP_DEVELOPER_GAME_DIR "%s")' % cfg["developer_exe_path"].parent.as_posix())
    lines.append('set(RECOMP_DEVELOPER_STAGE_DIR "%s")' % cfg["developer_stage_dir"].as_posix())
    lines.append('set(RECOMP_LAUNCHER_CONFIG_DIR "%s")' % cfg["launcher_config_dir"].as_posix())
    lines.append('set(RECOMP_DEVELOPER_EXE "%s")' % cfg["developer_exe_path"].as_posix())
    # [translate] native: C replacements for hot functions, compiled with the
    # translation. The header #defines FN_<addr> to each replacement (see the
    # override note in funcs.h); the sources define them.
    native = cfg["translate"].get("native", {})
    game_dir = Path(cfg["dir"])
    if native.get("header"):
        lines.append('set(RECOMP_NATIVE_HEADER "%s")' % (game_dir / native["header"]).resolve().as_posix())
        sources = [(game_dir / s).resolve().as_posix() for s in native.get("sources", ())]
        lines.append('set(RECOMP_NATIVE_SOURCES "%s")' % ";".join(sources))
        # addresses: a header only the native sources include (as
        # RECOMP_ADDRESS_HEADER) for the game's own addresses, so changing one
        # recompiles them and not the translation that includes the header above.
        addresses = native.get("addresses")
        lines.append('set(RECOMP_ADDRESS_HEADER "%s")'
                     % ((game_dir / addresses).resolve().as_posix() if addresses else ""))
    return "\n".join(lines) + "\n"


def write_if_changed(path, text):
    """UTF-8 whatever the locale: game.toml's strings are (Windows' would be cp1252)."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.is_file() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--game-dir", type=Path, required=True)
    parser.add_argument("--header", type=Path, required=True)
    parser.add_argument("--cmake", type=Path, required=True)
    args = parser.parse_args()
    cfg = game_config.load(args.game_dir)
    write_if_changed(args.header, render_header(cfg))
    write_if_changed(args.cmake, render_cmake(cfg))


if __name__ == "__main__":
    main()
